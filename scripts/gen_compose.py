"""Generate docker-compose.yml with one edge service and N explicitly pinned device services.

Usage: python scripts/gen_compose.py N [-o docker-compose.yml]

Devices are explicit services rather than `--scale` replicas because replicas share one
cpuset, which would break pinning each device to its own core.
"""

from __future__ import annotations

import argparse
import os
from pathlib import Path

import yaml

REPO_ROOT = Path(__file__).resolve().parent.parent
DEFAULT_OUTPUT = REPO_ROOT / "docker-compose.yml"

# Cores 0..RESERVED_CORES-1 stay unpinned for the OS and the edge; device-i gets the next one.
RESERVED_CORES = 2
DEVICE_CPUS = 0.25  # fraction of one core, emulates a Raspberry Pi
DEVICE_MEMORY = "512m"
EDGE_PORT = 50051
NETWORK = "edgenet"
HEADER = "# Generated by scripts/gen_compose.py. Do not edit by hand; do not use --scale.\n"


def device_core(index: int) -> int:
    """Host core that device-<index> (1-based) is pinned to."""
    return RESERVED_CORES + index - 1


def build_compose(n_devices: int, n_cores: int) -> dict:
    """Return the compose document for `n_devices` devices on a host with `n_cores` cores."""
    max_devices = n_cores - RESERVED_CORES
    if not 1 <= n_devices <= max_devices:
        raise ValueError(
            f"n_devices must be in [1, {max_devices}] on a {n_cores}-core host "
            f"({RESERVED_CORES} cores are reserved for the OS and the edge)"
        )
    services: dict[str, dict] = {
        "edge": {
            "build": {"context": ".", "dockerfile": "docker/Dockerfile.edge"},
            "image": "edgeinf-edge",
            "container_name": "edge",
            "gpus": "all",
            "environment": {"EDGE_PORT": EDGE_PORT},
            "networks": [NETWORK],
        }
    }
    for i in range(1, n_devices + 1):
        name = f"device-{i}"
        services[name] = {
            "build": {"context": ".", "dockerfile": "docker/Dockerfile.device"},
            "image": "edgeinf-device",
            "container_name": name,
            "cpuset": str(device_core(i)),
            "cpus": DEVICE_CPUS,
            "mem_limit": DEVICE_MEMORY,
            "cap_add": ["NET_ADMIN"],
            "environment": {"DEVICE_ID": name, "EDGE_ADDR": f"edge:{EDGE_PORT}"},
            "depends_on": ["edge"],
            "networks": [NETWORK],
        }
    return {"services": services, "networks": {NETWORK: {"driver": "bridge"}}}


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("n_devices", type=int, help="number of device containers")
    parser.add_argument("-o", "--output", type=Path, default=DEFAULT_OUTPUT)
    args = parser.parse_args()

    compose = build_compose(args.n_devices, os.cpu_count() or 1)
    args.output.write_text(HEADER + yaml.safe_dump(compose, sort_keys=False))
    print(f"wrote {args.output} with edge + {args.n_devices} device(s)")


if __name__ == "__main__":
    main()
