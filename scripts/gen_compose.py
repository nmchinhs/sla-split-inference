"""Generate docker-compose.yml with one edge service and N explicitly pinned device services.

Usage: python scripts/gen_compose.py N [-o docker-compose.yml]

Devices are explicit services rather than `--scale` replicas because replicas share one
cpuset, which would break pinning each device to its own core.

The CPU limit and the pinning order come from the calibration in experiments/calibration.md.
"""

from __future__ import annotations

import argparse
import os
from pathlib import Path

import yaml

REPO_ROOT = Path(__file__).resolve().parent.parent
DEFAULT_OUTPUT = REPO_ROOT / "docker-compose.yml"

# CPUs 0..RESERVED_CORES-1 are for the OS and the edge, which is pinned to them so that it can
# never run on a device's CPU; devices get the others.
RESERVED_CORES = 2
# Each device gets DEVICE_CPU_QUOTA_US of CPU time in every DEVICE_CPU_PERIOD_US: 21% of one CPU
# in slices of about 1 ms, which makes MobileNetV2 take about 100 ms as on a Raspberry Pi 4.
# Keep the share an exact whole percent: Docker's systemd cgroup driver rounds anything else up.
DEVICE_CPU_QUOTA_US = 1_050
DEVICE_CPU_PERIOD_US = 5_000
DEVICE_MEMORY = "512m"
CPU_TOPOLOGY = "/sys/devices/system/cpu/cpu{cpu}/topology/core_id"
EDGE_PORT = 50051
NETWORK = "edgenet"
HEADER = "# Generated by scripts/gen_compose.py. Do not edit by hand; do not use --scale.\n"


def device_cpus(core_of: list[int]) -> list[int]:
    """Host CPUs for device-1, device-2, ..., given the physical core of every host CPU.

    The first devices each get a physical core of their own. Only when those run out are the
    remaining hardware threads handed out, because two devices on the two threads of one core
    change each other's speed.
    """
    free = range(RESERVED_CORES, len(core_of))
    reserved = set(core_of[:RESERVED_CORES])
    first_thread, other_threads, seen = [], [], set(reserved)
    for cpu in free:
        (other_threads if core_of[cpu] in seen else first_thread).append(cpu)
        seen.add(core_of[cpu])
    return first_thread + other_threads


def read_core_of(n_cpus: int) -> list[int]:
    """Physical core id of each host CPU, from sysfs (each CPU its own core if unreadable)."""
    try:
        return [int(Path(CPU_TOPOLOGY.format(cpu=cpu)).read_text()) for cpu in range(n_cpus)]
    except OSError:
        return list(range(n_cpus))


def build_compose(n_devices: int, core_of: list[int]) -> dict:
    """Return the compose document for `n_devices` devices.

    `core_of[cpu]` is the physical core of host CPU `cpu`; it decides the pinning order.
    """
    cpus = device_cpus(core_of)
    if not 1 <= n_devices <= len(cpus):
        raise ValueError(
            f"n_devices must be in [1, {len(cpus)}] on a host with {len(core_of)} CPUs "
            f"({RESERVED_CORES} are reserved for the OS and the edge)"
        )
    services: dict[str, dict] = {
        "edge": {
            "build": {"context": ".", "dockerfile": "docker/Dockerfile.edge"},
            "image": "edgeinf-edge",
            "container_name": "edge",
            "gpus": "all",
            "cpuset": f"0-{RESERVED_CORES - 1}",
            "environment": {"EDGE_PORT": EDGE_PORT},
            "networks": [NETWORK],
        }
    }
    for i in range(1, n_devices + 1):
        name = f"device-{i}"
        services[name] = {
            "build": {"context": ".", "dockerfile": "docker/Dockerfile.device"},
            "image": "edgeinf-device",
            "container_name": name,
            "cpuset": str(cpus[i - 1]),
            "cpu_period": DEVICE_CPU_PERIOD_US,
            "cpu_quota": DEVICE_CPU_QUOTA_US,
            "mem_limit": DEVICE_MEMORY,
            "cap_add": ["NET_ADMIN"],
            "environment": {"DEVICE_ID": name, "EDGE_ADDR": f"edge:{EDGE_PORT}"},
            "depends_on": ["edge"],
            "networks": [NETWORK],
        }
    return {"services": services, "networks": {NETWORK: {"driver": "bridge"}}}


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("n_devices", type=int, help="number of device containers")
    parser.add_argument("-o", "--output", type=Path, default=DEFAULT_OUTPUT)
    args = parser.parse_args()

    compose = build_compose(args.n_devices, read_core_of(os.cpu_count() or 1))
    args.output.write_text(HEADER + yaml.safe_dump(compose, sort_keys=False))
    print(f"wrote {args.output} with edge + {args.n_devices} device(s)")


if __name__ == "__main__":
    main()
